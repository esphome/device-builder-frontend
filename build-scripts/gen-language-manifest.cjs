// Generate the language picker manifest from the translation files.
//
// The language picker (settings dialog + command palette) needs each
// locale's autonym (`language`) and `flag` up front, synchronously, to
// render. But the full message bodies are large (~80 KB each) and should
// load lazily, one chunk per locale, only when a locale is selected (see
// src/common/localize.ts). Eagerly importing every translation file just to
// read two keys would pull every locale's body into the entry bundle.
//
// So this script reads whatever `src/translations/*.json` exist and writes a
// tiny `src/generated/language-manifest.json` with `{ language, flag,
// completeness }` per locale. localize.ts statically imports that manifest
// (small, eager) and loads bodies lazily. The manifest is regenerated by the
// build/dev/lint/test entry points and is gitignored — there is no hardcoded
// locale list, so a downloaded locale lights up in the picker with no code
// change.
//
// `completeness` is the percentage of English source keys that locale has
// translated; the language picker surfaces it so users can see how finished a
// language is before switching to it (every untranslated key falls back to
// English at runtime).

const fs = require("fs");
const path = require("path");

// The locale helpers (`toBcp47`, `localeCompleteness`, the base-language
// constant) live once in translations-lib.ts, under the unit tests in
// test/build-scripts/translations-lib.test.ts. Node's native TypeScript type
// stripping together with `require(esm)` — both available on the `engines`
// floor (>= 22.18) — lets this CommonJS script require that ESM module
// synchronously, the same mechanism `node build-scripts/translations.ts`
// already relies on. `BASE_LANGUAGE` names the in-repo source-of-truth
// English file; completeness is measured against its key set.
let translationsLib;
try {
  translationsLib = require("./translations-lib.ts");
} catch (err) {
  // `engines` is only an install-time warning, so an unsupported Node still
  // reaches this require and dies with an opaque loader error (unknown `.ts`
  // extension or an ESM require failure). Name the actual floor instead.
  throw new Error(
    `Loading build-scripts/translations-lib.ts failed on Node ${process.version}; ` +
      "this script needs Node >= 22.18 (native TypeScript type stripping and require(esm)).",
    { cause: err }
  );
}
const { BASE_LANGUAGE, localeCompleteness, toBcp47 } = translationsLib;

const ROOT_DIR = path.resolve(__dirname, "..");
const TRANSLATIONS_DIR = path.join(ROOT_DIR, "src", "translations");
const OUTPUT_DIR = path.join(ROOT_DIR, "src", "generated");
const OUTPUT_FILE = path.join(OUTPUT_DIR, "language-manifest.json");

// Placeholder shown when a locale file lacks a translated `flag` key (the
// runtime picker uses the same white-flag fallback).
const FLAG_FALLBACK = "🏳️";

function generate() {
  const entries = fs
    .readdirSync(TRANSLATIONS_DIR)
    .filter((name) => name.endsWith(".json"))
    .sort();

  const basePath = path.join(TRANSLATIONS_DIR, `${BASE_LANGUAGE}.json`);
  const baseData = JSON.parse(fs.readFileSync(basePath, "utf-8"));

  const manifest = {};
  for (const name of entries) {
    const code = toBcp47(name.replace(/\.json$/, ""));
    const data = JSON.parse(
      fs.readFileSync(path.join(TRANSLATIONS_DIR, name), "utf-8")
    );
    manifest[code] = {
      language: typeof data.language === "string" ? data.language : code,
      flag: typeof data.flag === "string" ? data.flag : FLAG_FALLBACK,
      completeness: localeCompleteness(baseData, data),
    };
  }

  fs.mkdirSync(OUTPUT_DIR, { recursive: true });
  fs.writeFileSync(OUTPUT_FILE, `${JSON.stringify(manifest, null, 2)}\n`, "utf-8");
  return manifest;
}

module.exports = { generate };

if (require.main === module) {
  const manifest = generate();
  console.log(
    `Wrote ${path.relative(ROOT_DIR, OUTPUT_FILE)} (${Object.keys(manifest).join(", ")})`
  );
}
